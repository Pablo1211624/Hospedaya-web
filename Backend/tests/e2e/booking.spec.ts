import { test, expect } from '@playwright/test';
test('host publishes; guest books with demo payment, reloads and cancels', async ({ page }) => {
  const suffix = Date.now(), property = 'Casa E2E ' + suffix;
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  async function register(name: string, role: string) {
    await page.goto('/#/registro');
    await page.getByLabel('Nombre', { exact: true }).fill(name);
    await page.getByLabel('Tipo de cuenta').selectOption(role);
    await page.getByLabel('E-mail').fill(name + suffix + '@example.com');
    await page.getByLabel('Contraseña', { exact: true }).fill('Testing-only-password123');
    await page.getByLabel('Confirmar contraseña').fill('Testing-only-password123');
    await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Salir', exact: true })).toBeVisible();
  }
  await register('HostE2E', 'ANFITRION');
  await page.getByRole('link', { name: 'Añadir alojamiento', exact: true }).click();
  await page.getByLabel('Nombre', { exact: true }).fill(property);
  await page.getByLabel('Ciudad', { exact: true }).fill('Antigua');
  await page.getByLabel('Dirección', { exact: true }).fill('Calle de demostración 123');
  await page.getByLabel('Descripción', { exact: true }).fill('Casa de pruebas para integración de HospedaYa.');
  await page.getByRole('button', { name: 'Guardar alojamiento' }).click();
  await expect(page.getByRole('heading', { name: 'Disponibilidad', exact: true })).toBeVisible();
  await page.getByLabel('Desde', { exact: true }).fill('2090-01-01');
  await page.getByLabel('Hasta', { exact: true }).fill('2090-12-31');
  await page.getByRole('button', { name: 'Añadir período' }).click();
  await expect(page.getByText('2090-01-01 → 2090-12-31 · DISPONIBLE', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Salir', exact: true }).click();
  await register('GuestE2E', 'HUESPED');
  await page.screenshot({ path: '../.local/catalogo-desktop.png', fullPage: true });
  await page.getByRole('link').filter({ hasText: property }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: property, exact: true })).toBeVisible();
  await page.screenshot({ path: '../.local/detalle-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByLabel('Llegada', { exact: true }).fill('2090-05-01');
  await page.getByLabel('Salida', { exact: true }).fill('2090-05-04');
  await page.getByRole('button', { name: 'Reservar', exact: true }).click();
  await expect(page.getByRole('heading', { name: '1. Simulación de pago' })).toBeVisible();
  await page.getByLabel('Número de tarjeta de prueba').fill('1111 2222 3333 4444');
  await page.getByLabel('Vencimiento (mm/aaaa)').fill('12/2099');
  await page.getByLabel('CVV de prueba').fill('123');
  await page.getByLabel('Nombre de prueba', { exact: true }).fill('Persona Ficticia');
  await page.getByLabel('Código postal').fill('01001');
  await page.getByLabel('CVV de prueba').fill('12');
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('CVV de prueba debe tener 3 o 4');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../.local/pago-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByLabel('CVV de prueba').fill('123');
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
  await expect(page.getByLabel('CVV de prueba')).toHaveCount(0);
  const outgoing = page.waitForRequest(r => r.url().endsWith('/api/reservas') && r.method() === 'POST');
  await page.getByRole('button', { name: 'Confirmar reserva', exact: true }).click();
  expect(Object.keys((await outgoing).postDataJSON()).sort()).toEqual(['adultos', 'alojId', 'desde', 'hasta', 'ninos']);
  await expect(page.getByText(/Pago ficticio: no se realizó ningún cobro/)).toBeVisible();
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  expect(storage).not.toContain('1111'); expect(storage).not.toContain('Persona Ficticia');
  await page.screenshot({ path: '../.local/confirmacion-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Ver mis reservas' }).click();
  await page.reload();
  await expect(page.getByText(property, { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Modificar', exact: true }).click();
  await page.getByLabel('Llegada', { exact: true }).fill('2090-06-01');
  await page.getByLabel('Salida', { exact: true }).fill('2090-06-03');
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await expect(page.getByText(/2090-06-01 → 2090-06-03/)).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../.local/reservas-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByText('Cancelada', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Sobre mí', exact: true }).click();
  await page.getByLabel('Biografía', { exact: true }).fill('Perfil de prueba guardado.');
  await page.getByRole('button', { name: 'Guardar perfil', exact: true }).click();
  await expect(page.getByText('Perfil actualizado.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Biografía', { exact: true })).toHaveValue('Perfil de prueba guardado.');
  await page.getByRole('button', { name: 'Salir', exact: true }).click();
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click();
  await page.getByLabel('E-mail').fill('GuestE2E' + suffix + '@example.com');
  await page.getByLabel('Contraseña', { exact: true }).fill('wrong-password123');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Correo o contraseña incorrectos.');
  await page.getByLabel('Contraseña', { exact: true }).fill('Testing-only-password123');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Salir', exact: true })).toBeVisible();
  await page.goto('/#/anfitrion');
  await expect(page.getByText('Esta sección requiere una cuenta de anfitrión.')).toBeVisible();
  expect(errors).toEqual([]);
});

test('muestra errores de conexión y permite recuperar la pantalla', async ({ page }) => {
  await page.route('**/api/alojamientos', route => route.abort());
  await page.goto('/#/');
  await expect(page.getByRole('alert')).toContainText('No se pudo conectar con el servidor');
  await page.unroute('**/api/alojamientos');
  await page.reload();
  await expect(page.getByText('Buscando alojamientos…')).toHaveCount(0);
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.evaluate(() => sessionStorage.setItem('hospedaya.token', 'invalid-session'));
  await page.goto('/#/perfil');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('hospedaya.token'))).toBeNull();
});
